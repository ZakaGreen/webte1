// Keep the chosen language in the URL so navigation and shared links retain it.
const languageSelect = document.querySelector('#language');
const requestedLanguage = new URLSearchParams(window.location.search).get('lang');
const language = ['sk', 'en', 'ru'].includes(requestedLanguage) ? requestedLanguage : 'sk';

// Insert values such as a lesson name or distance into a translated message.
function translate(key, values = {}) {
  let text = translations[key][language];
  Object.entries(values).forEach(([name, value]) => {
    text = text.replaceAll('{' + name + '}', () => value);
  });
  return text;
}

document.documentElement.lang = language;
document.querySelectorAll('[data-i18n]').forEach(element => {
  const text = translate(element.dataset.i18n);
  if (element.tagName === 'META') element.content = text;
  else if (element.tagName === 'IMG') element.alt = text;
  else element.innerHTML = text; // Only the fixed dictionary contains HTML, never user input.
});

document.querySelectorAll('a[href]').forEach(link => {
  if (link.getAttribute('href').startsWith('#')) return;
  const url = new URL(link.href);
  if (url.origin === window.location.origin && url.pathname.endsWith('.html')) {
    url.searchParams.set('lang', language);
    link.href = url.href;
  }
});

languageSelect.value = language;
languageSelect.parentElement.hidden = false;
// Reload the same page in the selected language, including its interactive messages.
languageSelect.addEventListener('change', () => {
  const url = new URL(window.location.href);
  url.searchParams.set('lang', languageSelect.value);
  window.location.href = url.href;
});
